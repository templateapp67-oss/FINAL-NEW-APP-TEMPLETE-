export type SiteBookingI18nKey = keyof typeof EN;

export function bookingFlowText(locale: AppLocale): Record<SiteBookingI18nKey, string> {
  return locale === 'hi' ? HI : EN;
}

/** Formats a phrase with a single placeholder. */
export function fillBookingText(template: string, values: Record<string, string | number>): string {
  return Object.entries(values).reduce(
    (out, [key, value]) => out.split(`{${key}}`).join(String(value)),
    template,
  );
}
