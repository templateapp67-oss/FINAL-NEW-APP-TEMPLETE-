/** The single global entry point: all copy for one theme in one locale. */
export function siteText(themeId: SiteHeaderThemeId, locale: AppLocale): Record<string, string> {
  const table = THEME_TEXT[themeId] || THEME_TEXT.barber_mens_grooming;
  return { ...(locale === 'hi' ? COMMON_HI : COMMON_EN), ...table[locale === 'hi' ? 'hi' : 'en'] };
}

/** Translates a {en, hi} service/category-like static label lists. */
export function pick<T extends string>(locale: AppLocale, en: T, hi: string): string {
  return locale === 'hi' ? hi : en;
}
