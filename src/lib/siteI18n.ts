/** Weekday + schedule labels. */
export const DAY_LABELS: Record<string, Record<AppLocale, string>> = {
  monday: { en: 'Monday', hi: 'सोमवार' },
  tuesday: { en: 'Tuesday', hi: 'मंगलवार' },
  wednesday: { en: 'Wednesday', hi: 'बुधवार' },
  thursday: { en: 'Thursday', hi: 'गुरुवार' },
  friday: { en: 'Friday', hi: 'शुक्रवार' },
  saturday: { en: 'Saturday', hi: 'शनिवार' },
  sunday: { en: 'Sunday', hi: 'रविवार' },
};

export function dayLabel(day: string, locale: AppLocale): string {
  const hit = DAY_LABELS[day.toLowerCase()];
  if (hit) return hit[locale];
  return day.charAt(0).toUpperCase() + day.slice(1);
}

